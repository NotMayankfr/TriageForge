"""
TriageForge Data Models
Type-safe representations for evidence, diagnostic layers, hypotheses, and reports.
"""

from __future__ import annotations
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CheckStatus(str, Enum):
    OK = "OK"
    WARN = "WARN"
    FAIL = "FAIL"
    SKIPPED = "SKIPPED"


class Evidence(BaseModel):
    """A concrete piece of observed diagnostic data from a diagnostic layer."""
    layer: str
    metric: str
    status: CheckStatus
    observed: Any
    expected: Optional[Any] = None
    message: str
    weight: float = Field(default=1.0, description="Relevance weight (0.0 to 2.0) in hypothesis scoring")


class LayerResult(BaseModel):
    """Aggregated output from a single layer inspection."""
    layer_name: str
    status: CheckStatus
    duration_ms: float
    evidence: List[Evidence] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    error_message: Optional[str] = None


class Hypothesis(BaseModel):
    """A deterministic, evidence-backed candidate failure hypothesis."""
    fault_type: str
    title: str
    confidence: float = Field(ge=0.0, le=1.0, description="Deterministic confidence score between 0.0 and 1.0")
    severity: str = Field(default="SEV-2", description="Incident severity level (SEV-1, SEV-2, SEV-3)")
    category: str = Field(description="Layer category: Network, Compute, Storage, Database, Security, Application")
    root_cause: str
    supporting_evidence: List[str] = Field(default_factory=list)
    contradicting_evidence: List[str] = Field(default_factory=list)
    next_best_command: str = Field(description="Exact command an L2/L3 SRE should execute to verify or drill down")
    remediation_summary: str = Field(description="Immediate mitigation or fix action")


class DiagnosticReport(BaseModel):
    """Full end-to-end diagnostic report generated by TriageForge."""
    target_url: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    execution_time_ms: float
    layers: Dict[str, LayerResult] = Field(default_factory=dict)
    all_evidence: List[Evidence] = Field(default_factory=list)
    hypotheses: List[Hypothesis] = Field(default_factory=list)
    top_hypothesis: Optional[Hypothesis] = None
    is_healthy: bool = False
    executive_summary: str = ""

    def get_top_fault_type(self) -> Optional[str]:
        return self.top_hypothesis.fault_type if self.top_hypothesis else None
